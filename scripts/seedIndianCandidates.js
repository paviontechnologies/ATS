async function seedIndianCandidates() {
  console.log('====================================================');
  console.log('🇮🇳 SEEDING 50 DIVERSE INDIAN PROFILES INTO ENTERPRISE ATS');
  console.log('====================================================\n');

  if (!fs.existsSync(ATS_DB_PATH)) {
    console.error(`Database not found at ${ATS_DB_PATH}`);
    process.exit(1);
  }

  const rawData = fs.readFileSync(ATS_DB_PATH, 'utf-8');
  const db = JSON.parse(rawData);

  if (!db.candidates) db.candidates = [];
  if (!db.applications) db.applications = [];
  if (!db.interviews) db.interviews = [];
  if (!db.scorecards) db.scorecards = [];
  if (!db.offers) db.offers = [];

  const tenantId = db.companies?.[0]?._id || 'doc_a71bf70ad6ed56ce';
  const jobsList = db.jobs || [];

  console.log(`Found ${jobsList.length} jobs in database.`);
  console.log(`Existing candidates before seed: ${db.candidates.length}`);
  console.log(`Existing applications before seed: ${db.applications.length}`);

  let addedCandidates = 0;
  let addedApplications = 0;
  let addedInterviews = 0;
  let addedScorecards = 0;
  let addedOffers = 0;

  for (let i = 0; i < INDIAN_CANDIDATES_DATA.length; i++) {
    const item = INDIAN_CANDIDATES_DATA[i];
    
    // Check if candidate already exists by email
    let candidate = db.candidates.find(c => c.email.toLowerCase() === item.email.toLowerCase());
    
    const candidateId = candidate?._id || `doc_cand_ind_${Date.now().toString(36)}_${i}_${crypto.randomBytes(3).toString('hex')}`;

    if (!candidate) {
      candidate = {
        _id: candidateId,
        createdAt: new Date(Date.now() - (50 - i) * 86400000).toISOString(),
        updatedAt: new Date().toISOString(),
        tenantId,
        firstName: item.firstName,
        lastName: item.lastName,
        email: item.email,
        phone: item.phone,
        location: {
          city: item.city,
          state: item.state,
          country: item.country
        },
        skills: item.skills,
        totalExperienceYears: item.totalExperienceYears,
        summary: item.summary,
        tags: item.tags,
        source: item.source,
        education: [
          {
            institution: item.institution,
            degree: item.degree,
            graduationYear: item.graduationYear
          }
        ],
        workHistory: [
          {
            company: item.currentCompany,
            title: item.currentTitle,
            startDate: `${item.graduationYear + 1}-06-01`,
            isCurrent: true
          }
        ]
      };
      db.candidates.push(candidate);
      addedCandidates++;
    }

    // Match candidate to an appropriate job
    let matchingJob = jobsList.find(j => j.title.toLowerCase().includes(item.targetJobTitle.toLowerCase())) 
      || jobsList[i % jobsList.length] 
      || { _id: 'doc_bbe4c6051f27d640', title: 'Senior Full-Stack Engineer' };

    // Check if application exists
    let application = db.applications.find(a => a.candidateId === candidate._id && a.jobId === matchingJob._id);

    if (!application) {
      const appId = `doc_app_ind_${Date.now().toString(36)}_${i}_${crypto.randomBytes(3).toString('hex')}`;
      const isKnockoutPass = item.stage !== 'Rejected';

      application = {
        _id: appId,
        createdAt: candidate.createdAt,
        updatedAt: new Date().toISOString(),
        tenantId,
        jobId: matchingJob._id,
        candidateId: candidate._id,
        stageId: item.stage,
        status: item.stage === 'Rejected' ? 'REJECTED' : (item.stage === 'Hired' ? 'HIRED' : 'ACTIVE'),
        knockoutStatus: isKnockoutPass ? 'PASSED' : 'DISQUALIFIED',
        aiMatchScore: {
          overallScore: item.overallScore,
          skillsScore: Math.min(99, item.overallScore + 2),
          experienceScore: Math.max(60, item.overallScore - 3),
          educationScore: Math.min(98, item.overallScore + 1),
          semanticScore: item.overallScore,
          matchingSkills: item.skills.slice(0, 4),
          missingSkills: isKnockoutPass ? [] : ["full_stack_5yr_mandatory"],
          recommendation: item.recommendation,
          explanation: item.explanation,
          calculatedAt: new Date().toISOString()
        },
        stageHistory: [
          { fromStage: 'Applied', toStage: 'Applied', changedAt: candidate.createdAt },
          ...(item.stage !== 'Applied' ? [{ fromStage: 'Applied', toStage: 'Screening', changedAt: new Date(Date.now() - (45 - i) * 86400000).toISOString() }] : []),
          ...(item.stage === 'Shortlisted' || item.stage === 'Interview' || item.stage === 'Offer' || item.stage === 'Hired' ? [{ fromStage: 'Screening', toStage: 'Shortlisted', changedAt: new Date(Date.now() - (35 - i) * 86400000).toISOString() }] : []),
          ...(item.stage === 'Interview' || item.stage === 'Offer' || item.stage === 'Hired' ? [{ fromStage: 'Shortlisted', toStage: 'Interview', changedAt: new Date(Date.now() - (20 - i) * 86400000).toISOString() }] : []),
          ...(item.stage === 'Offer' || item.stage === 'Hired' ? [{ fromStage: 'Interview', toStage: 'Offer', changedAt: new Date(Date.now() - (10 - i) * 86400000).toISOString() }] : []),
          ...(item.stage === 'Hired' ? [{ fromStage: 'Offer', toStage: 'Hired', changedAt: new Date(Date.now() - (2) * 86400000).toISOString() }] : []),
          ...(item.stage === 'Rejected' ? [{ fromStage: 'Applied', toStage: 'Rejected', changedAt: new Date(Date.now() - (40 - i) * 86400000).toISOString() }] : [])
        ]
      };
      db.applications.push(application);
      addedApplications++;

      // If candidate is in Interview stage, create an interview schedule
      if (item.stage === 'Interview') {
        const interviewId = `doc_int_ind_${Date.now().toString(36)}_${i}`;
        const interview = {
          _id: interviewId,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
          tenantId,
          applicationId: application._id,
          roundName: `${matchingJob.title} - Technical Round 1 (System Architecture & Coding)`,
          interviewerIds: ["doc_f498dda4a79ee504", "doc_493030e468962233"],
          scheduledStartTime: new Date(Date.now() + (i * 3600000)).toISOString(),
          scheduledEndTime: new Date(Date.now() + (i * 3600000) + 3600000).toISOString(),
          meetingUrl: `https://meet.google.com/ats-ind-${item.firstName.toLowerCase()}-${item.lastName.toLowerCase()}`,
          calendarEventId: `cal_event_ind_${i}`,
          status: 'SCHEDULED'
        };
        db.interviews.push(interview);
        addedInterviews++;

        // Add scorecard for every second interview
        if (i % 2 === 0) {
          const scorecard = {
            _id: `doc_sc_ind_${Date.now().toString(36)}_${i}`,
            createdAt: new Date().toISOString(),
            updatedAt: new Date().toISOString(),
            tenantId,
            interviewId: interview._id,
            interviewerId: "doc_f498dda4a79ee504",
            interviewerName: "Elena Rostova",
            criteriaRatings: [
              { name: "Technical Depth", score: 5, feedback: "Solid command of low-level principles and concurrent programming." },
              { name: "System Architecture", score: 4, feedback: "Designed modular API boundaries and distributed queues." },
              { name: "Communication & Articulation", score: 5, feedback: "Structured, patient, and precise communicator." },
              { name: "Culture & Ownership", score: 5, feedback: "High accountability and strong customer obsession." }
            ],
            overallRecommendation: "STRONG_YES",
            privateNotes: `Top-tier candidate from ${item.institution}. Recommend expedited final offer.`,
            isSubmitted: true,
            submittedAt: new Date().toISOString()
          };
          db.scorecards.push(scorecard);
          addedScorecards++;
        }
      }

      // If candidate is in Offer stage, create an official offer package
      if (item.stage === 'Offer') {
        const salaryInINR = Math.round((item.totalExperienceYears * 350000) + 1200000);
        const offer = {
          _id: `doc_off_ind_${Date.now().toString(36)}_${i}`,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
          tenantId,
          applicationId: application._id,
          candidateId: candidate._id,
          jobTitle: matchingJob.title,
          baseSalary: salaryInINR,
          currency: "INR",
          variableBonus: Math.round(salaryInINR * 0.15),
          equityShares: Math.round(item.totalExperienceYears * 5000),
          targetStartDate: new Date(Date.now() + 1296000000).toISOString(),
          expirationDate: new Date(Date.now() + 604800000).toISOString(),
          approvalStatus: "APPROVED",
          candidateDecision: "SENT",
          sentAt: new Date().toISOString(),
          signedOffBy: "Alex Morgan",
          signedOffAt: new Date().toISOString(),
          managerNotes: `Executive offer generated for ${item.firstName} ${item.lastName} (CTC: ₹${(salaryInINR / 100000).toFixed(1)} LPA). Approved via Compensation Committee.`
        };
        db.offers.push(offer);
        addedOffers++;
      }
    }
  }

  // Save to ats_database.json
  fs.writeFileSync(ATS_DB_PATH, JSON.stringify(db, null, 2), 'utf-8');
  console.log(`✅ Successfully updated ${ATS_DB_PATH}`);

  // Also sync to ats_mysql_storage.json
  if (fs.existsSync(ATS_MYSQL_PATH)) {
    try {
      const mysqlRaw = fs.readFileSync(ATS_MYSQL_PATH, 'utf-8');
      const mysqlStorage = JSON.parse(mysqlRaw);
      mysqlStorage.candidates = [...db.candidates];
      mysqlStorage.applications = [...db.applications];
      mysqlStorage.interviews = [...db.interviews];
      mysqlStorage.scorecards = [...db.scorecards];
      mysqlStorage.offers = [...db.offers];
      fs.writeFileSync(ATS_MYSQL_PATH, JSON.stringify(mysqlStorage, null, 2), 'utf-8');
      console.log(`✅ Successfully updated ${ATS_MYSQL_PATH}`);
    } catch (e) {
      console.warn(`Could not sync to mysql storage: ${e.message}`);
    }
  }

  console.log('\n----------------------------------------------------');
  console.log(`🎉 Seeding Summary:`);
  console.log(`   👤 Indian Candidates Added: ${addedCandidates} (Total: ${db.candidates.length})`);
  console.log(`   📋 Pipeline Applications:   ${addedApplications} (Total: ${db.applications.length})`);
  console.log(`   📅 Scheduled Interviews:     ${addedInterviews} (Total: ${db.interviews.length})`);
  console.log(`   ⭐ Frozen Scorecards:       ${addedScorecards} (Total: ${db.scorecards.length})`);
  console.log(`   💼 Executive Offer Packages: ${addedOffers} (Total: ${db.offers.length})`);
  console.log('----------------------------------------------------');
}

seedIndianCandidates().catch(err => {
  console.error('Fatal error during Indian candidates seeding:', err);
  process.exit(1);
});
